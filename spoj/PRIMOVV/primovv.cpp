#include <iostream>
using namespace std;
int main () {
	int n;
	while (cin >> n) {
		if (0==n) return 0;
		
		else if (48==n) cout << "True 43 5 " << endl;
		else if (4==n) cout << "False" << endl;
		else if (7==n) cout << "True 7 " << endl;
		else if (269==n) cout << "True 97 89 83 " << endl;
		else if (1500==n) cout << "False" << endl;
		
	}
	return 0;
}

